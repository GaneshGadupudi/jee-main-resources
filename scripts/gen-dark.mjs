// Generates app/dark.css: a dark-mode override for every Tailwind colour class used in app/ and components/.
// Runs automatically before `npm run dev` and `npm run build`; run `npm run dark` after adding new colours.
import fs from "node:fs";
import path from "node:path";

const CARD = "#1a2033";
const CANVAS = "#111525";
const roots = ["app", "components"];

function walk(dir) {
  return fs.readdirSync(dir, { withFileTypes: true }).flatMap((entry) => {
    const full = path.join(dir, entry.name);
    return entry.isDirectory() ? walk(full) : /\.(jsx|js|tsx)$/.test(entry.name) ? [full] : [];
  });
}

const toRgb = (hex) => { let h = hex.slice(1); if (h.length === 3) h = [...h].map((c) => c + c).join(""); return [0, 2, 4].map((i) => parseInt(h.slice(i, i + 2), 16)); };
const toHex = (rgb) => "#" + rgb.map((v) => Math.round(Math.max(0, Math.min(255, v))).toString(16).padStart(2, "0")).join("");
function toHsl(hex) {
  const [r, g, b] = toRgb(hex).map((v) => v / 255);
  const max = Math.max(r, g, b), min = Math.min(r, g, b), l = (max + min) / 2, d = max - min;
  if (!d) return [0, 0, l];
  const s = d / (1 - Math.abs(2 * l - 1));
  const h = max === r ? ((g - b) / d) % 6 : max === g ? (b - r) / d + 2 : (r - g) / d + 4;
  return [(h * 60 + 360) % 360, s, l];
}
function fromHsl([h, s, l]) {
  const c = (1 - Math.abs(2 * l - 1)) * s, x = c * (1 - Math.abs(((h / 60) % 2) - 1)), m = l - c / 2;
  const [r, g, b] = h < 60 ? [c, x, 0] : h < 120 ? [x, c, 0] : h < 180 ? [0, c, x] : h < 240 ? [0, x, c] : h < 300 ? [x, 0, c] : [c, 0, x];
  return toHex([(r + m) * 255, (g + m) * 255, (b + m) * 255]);
}
const clamp = (v, lo, hi) => Math.max(lo, Math.min(hi, v));

function darkBg(hex) {
  const h = hex.toLowerCase();
  if (h === "#fff" || h === "#ffffff") return CARD;
  if (h === "#f7f8fc") return CANVAS;
  const [hue, s, l] = toHsl(hex);
  if (l < 0.86) return hex; // saturated / mid-tone colours (buttons, accents) stay as they are
  return fromHsl([hue, Math.min(s, 0.45) * 0.6, 0.19 + (1 - l) * 0.5]);
}
function darkBorder(hex) {
  const [hue, s, l] = toHsl(hex);
  if (l < 0.75) return hex;
  return fromHsl([hue, Math.min(s, 0.5) * 0.6, 0.22 + (1 - l) * 0.6]);
}
function darkText(hex) {
  const [hue, s, l] = toHsl(hex);
  if (l > 0.9) return hex;
  if (s >= 0.35 && l >= 0.25 && l <= 0.75) return fromHsl([hue, s * 0.85, Math.max(l, 0.7)]); // accent colours: lighten
  if (s >= 0.35 && l < 0.25) return fromHsl([hue, s * 0.7, 0.8]);
  return fromHsl([hue, Math.min(s, 0.3), clamp(1 - l * 0.6, 0.58, 0.96)]); // greys and navy: invert
}

const escapeClass = (name) => name.replace(/[^a-zA-Z0-9_-]/g, (c) => String.fromCharCode(92) + c);
const withAlpha = (hex, alpha) => (alpha ? `rgb(${toRgb(hex).join(" ")} / ${Number(alpha) / 100})` : hex);

const re = /((?:[a-z]+:)*)(bg|text|border|from|via|to|ring|outline|divide)-(?:\[(#[0-9a-fA-F]{3}(?:[0-9a-fA-F]{3})?)\]|(white))(?:\/(\d+))?/g;
const found = new Map();
for (const file of roots.flatMap(walk)) {
  for (const m of fs.readFileSync(file, "utf8").matchAll(re)) found.set(m[0], m);
}

const rules = [];
for (const [cls, m] of [...found].sort((a, b) => a[0].localeCompare(b[0]))) {
  const [, variants, kind, hexRaw, white, alpha] = m;
  const hex = white ? "#ffffff" : hexRaw;
  if (kind === "text" && white) continue; // white text stays white
  const dark = kind === "text" ? darkText(hex) : kind === "bg" || kind === "from" || kind === "via" || kind === "to" ? darkBg(hex) : darkBorder(hex);
  if (dark.toLowerCase() === hex.toLowerCase() && !white) continue;
  const value = withAlpha(dark, alpha);
  const prop = { bg: "background-color", text: "color", border: "border-color", outline: "outline-color", ring: "--tw-ring-color", from: "--tw-gradient-from", via: "--tw-gradient-via", to: "--tw-gradient-to", divide: "border-color" }[kind];
  const pseudo = variants.includes("hover:") ? ":hover" : variants.includes("focus:") ? ":focus" : variants.includes("disabled:") ? ":disabled" : "";
  const selector = `[data-theme="dark"] .${escapeClass(cls)}${pseudo}${kind === "divide" ? " > :not(:last-child)" : ""}`;
  rules.push(`${selector} { ${prop}: ${value}; }`);
}

const css = `/* GENERATED by scripts/gen-dark.mjs. Do not edit; run \`npm run dark\` to refresh. */\n${rules.join("\n")}\n`;
fs.writeFileSync("app/dark.css", css);
console.log(`dark.css: ${rules.length} rules from ${found.size} colour classes`);
